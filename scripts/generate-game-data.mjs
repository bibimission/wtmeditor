// Regenerates src/shared/gameData.generated.js from the Brothel King sources.
// Usage: npm run generate:game-data [-- <path to the game/ folder>]
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const here = path.dirname(fileURLToPath(import.meta.url));
const output = path.join(here, "..", "src", "shared", "gameData.generated.js");
const gameDir =
  process.argv[2] ||
  process.env.BK_GAME_DIR ||
  "D:/Jeux/Flash/BrothelKing/Brothel_King-pc-0.3t.2/Brothel_King-pc/game";

function stripComment(line) {
  let inString = false;
  for (let i = 0; i < line.length; i++) {
    if (line[i] === '"') inString = !inString;
    if (line[i] === "#" && !inString) return line.slice(0, i);
  }
  return line;
}

function strings(text) {
  return [...text.matchAll(/"([^"]*)"/g)].map((m) => m[1]);
}

function readTagDict(file) {
  const lines = fs.readFileSync(file, "utf8").split(/\r?\n/);
  const start = lines.findIndex((l) => /^\s*tag_dict\s*=\s*\{/.test(l));
  if (start < 0) throw new Error("tag_dict not found in " + file);

  const dict = {};
  for (let i = start + 1; i < lines.length; i++) {
    const line = stripComment(lines[i]).trim();
    if (line === "}") return dict;
    if (!line) continue;
    const [key, ...values] = strings(line);
    if (key === undefined || values.length === 0) {
      throw new Error(`Unreadable tag_dict line ${i + 1}: ${line}`);
    }
    dict[key] = values;
  }
  throw new Error("Unterminated tag_dict in " + file);
}

function readFormats(file, name) {
  const pattern = new RegExp(`^\\s*${name}\\s*=\\s*\\(([^)]*)\\)`, "m");
  const match = fs.readFileSync(file, "utf8").match(pattern);
  if (!match) throw new Error(`${name} not found in ${file}`);
  return strings(match[1]);
}

const tagDict = readTagDict(path.join(gameDir, "BKsettings.rpy"));
const variables = path.join(gameDir, "BKinit_variables.rpy");

const body = [
  "// GENERATED by scripts/generate-game-data.mjs: do not edit by hand.",
  "// Sources: BKsettings.rpy (tag_dict), BKinit_variables.rpy (IMGFORMATS, VIDEOFORMATS).",
  "",
  `export const TAG_DICT = ${JSON.stringify(tagDict, null, 2)};`,
  "",
  `export const IMAGE_FORMATS = ${JSON.stringify(readFormats(variables, "IMGFORMATS"))};`,
  "",
  `export const VIDEO_FORMATS = ${JSON.stringify(readFormats(variables, "VIDEOFORMATS"))};`,
  "",
].join("\n");

fs.writeFileSync(output, body);
console.log(`${Object.keys(tagDict).length} tags written to ${path.relative(process.cwd(), output)}`);
